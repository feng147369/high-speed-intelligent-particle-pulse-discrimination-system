`timescale 1ns / 1ps
//***********************************************************************************************************************
//***********************************************************************************************************************



// Clock_Monitor  125.00Mhz   125000  (124970,125030)
// Clock_Monitor  156.25Mhz   156250  (156220,156280)
// Clock_Monitor  250.00Mhz   250000  (249970,250030)
// Clock_Monitor  312.50Mhz   312500  (312470,312530)
//***********************************************************************************************************************
//***********************************************************************************************************************
module Clock_Monitor_Generator_mod #
(
   parameter Clock_Monitor_Khz  = 156250,
	parameter Error_Monitor_Khz  = 300
)
(
  input   			clk_50m,       // 五十兆时钟
  input   			Clock_Monitor, // 被测时钟
  input   			sys_rst_n,     // 低有效复位
  
  output  [31:0]  Clock_Monitor_fre,  // 时钟频率值
  output  			Monitor_rst_n1,  // 监控复位一
  output  			Monitor_rst_n2,  // 监控复位二
  output  			Monitor_rst_n3,  // 监控复位三
  output  			Monitor_rst_n4,  // 监控复位四
  output  			Monitor_rst_n5,  // 监控复位五
  output  			Monitor_rst_n6,  // 监控复位六
  output  			Monitor_rst_n7,  // 监控复位七
  output  			Monitor_rst_n8  // 监控复位八
);
//***********************************************************************************************************************
//***********************************************************************************************************************
localparam  Min_cnt  = (Clock_Monitor_Khz-Error_Monitor_Khz);
localparam  Max_cnt  = (Clock_Monitor_Khz+Error_Monitor_Khz);
localparam  Time_1ms = 32'd50000;
localparam  Time_rst = 32'd100000;
//***********************************************************************************************************************
//***********************************************************************************************************************
reg [31:0] cnt=32'd0;
always @ (posedge clk_50m)
begin
  if(!sys_rst_n)
    cnt<=32'd0;
  else if(cnt<32'd1000000)
    cnt<=cnt+32'd1;
  else
    cnt<=32'd0;
end
wire Flag_1ms;
assign Flag_1ms=(cnt==Time_1ms)?1'b1:1'b0;
//***********************************************************************************************************************
//***********************************************************************************************************************
reg Flag_reg1,Flag_reg2;
always @ (posedge Clock_Monitor)
begin
   Flag_reg1<=Flag_1ms;
	Flag_reg2<=Flag_reg1;	
end
wire Flag_pos,Flag_neg;
assign Flag_neg = Flag_reg2 & (~Flag_reg1);
assign Flag_pos = Flag_reg1 & (~Flag_reg2);
//***********************************************************************************************************************
//***********************************************************************************************************************
reg [31:0] cnt_sys=32'd0;
(* ASYNC_REG="TRUE" *)reg [31:0] cnt_fre=32'd0;
always @ (posedge Clock_Monitor)
begin
  if(!sys_rst_n)
    cnt_sys<=32'd0;
  else  if(cnt<32'd990000)
  begin
  if(cnt==32'd0)
    cnt_sys<=32'd0; 
  else if(Flag_pos==1'b1)
    cnt_fre<=cnt_sys;
  else
    cnt_sys<=cnt_sys+1; 
  end
  else
  begin
    cnt_fre<=cnt_fre;
  end
end
//***********************************************************************************************************************
//***********************************************************************************************************************
(* ASYNC_REG="TRUE" *)reg Flag_rst_reg;
always @ (posedge clk_50m)
begin
  if(!sys_rst_n)
    Flag_rst_reg<=1'b0;
  else if((cnt_fre>Min_cnt) &&(cnt_fre<Max_cnt))
	   Flag_rst_reg<=1'b0;
  else
    Flag_rst_reg<=1'b1;
end
reg [31:0] cnt_rst=32'd0;
always @ (posedge clk_50m)
begin
  if(!sys_rst_n)
    cnt_rst<=32'd0;
  else if(Flag_rst_reg==1'b1)
	 if(cnt_rst<50000)
	 begin
	   cnt_rst<=cnt_rst+1;
	 end
	 else
	 begin
	   cnt_rst<=32'd0;
	 end
  else
  begin
    cnt_rst<=32'd0;
  end
end
assign Clock_Monitor_fre=cnt_fre;
////***********************************************************************************************************************
////***********************************************************************************************************************
assign Monitor_rst_n1=((cnt_rst>32'd1000)&&(cnt_rst<32'd1900))?1'b0:1'b1;
assign Monitor_rst_n2=((cnt_rst>32'd2000)&&(cnt_rst<32'd2900))?1'b0:1'b1;
assign Monitor_rst_n3=((cnt_rst>32'd3000)&&(cnt_rst<32'd3900))?1'b0:1'b1;
assign Monitor_rst_n4=((cnt_rst>32'd4000)&&(cnt_rst<32'd4900))?1'b0:1'b1;
assign Monitor_rst_n5=((cnt_rst>32'd5000)&&(cnt_rst<32'd5900))?1'b0:1'b1;
assign Monitor_rst_n6=((cnt_rst>32'd6000)&&(cnt_rst<32'd6900))?1'b0:1'b1;
assign Monitor_rst_n7=((cnt_rst>32'd7000)&&(cnt_rst<32'd7900))?1'b0:1'b1;
assign Monitor_rst_n8=((cnt_rst>32'd8000)&&(cnt_rst<32'd8900))?1'b0:1'b1;
//***********************************************************************************************************************
//***********************************************************************************************************************
//***********************************************************************************************************************
//***********************************************************************************************************************
endmodule
